function segsOf(p) {
  return String(p || "").split("/").filter(Boolean);
}

/**
 * 把旧版站点根路径解析成 /mesrj 下的等价路径。
 * @param {string} path req.path（不含查询串）
 * @returns {string|null} 形如 "/exec/pass"；无对应实现返回 null
 */
export function legacyMesrjTarget(path) {
  const segs = segsOf(path);
  if (!segs.length) return null;
  if (segs.some(s => s.includes("."))) return null;
  const lower = segs.map(s => s.toLowerCase());
  const renamed = LEGACY_RENAMES.get("/" + lower.join("/"));
  if (renamed) return renamed;
  for (const tpl of LEGACY_SHAPES) {
    if (tpl.length !== segs.length) continue;
    let hit = true;
    for (let i = 0; i < tpl.length; i += 1) {
      const t = tpl[i];
      if (t === null) continue;
      if (t.toLowerCase() !== lower[i]) { hit = false; break; }
    }
    if (hit) return "/" + segs.join("/");
  }
  return null;
}
